interface LanguageContextValue {
  language: Language
  setLanguage: (language: Language) => void
  toggleLanguage: () => void
  translate: (text: string) => string
}

const defaultContext: LanguageContextValue = {
  language: 'en',
  setLanguage: () => undefined,
  toggleLanguage: () => undefined,
  translate: (text) => text,
}

const LanguageContext = createContext<LanguageContextValue>(defaultContext)

function getInitialLanguage(): Language {
  const storedLanguage = window.localStorage.getItem(languageStorageKey)
  if (storedLanguage === 'en' || storedLanguage === 'th') return storedLanguage
  return window.navigator.language.toLowerCase().startsWith('th') ? 'th' : 'en'
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(getInitialLanguage)

  useEffect(() => {
    document.documentElement.lang = language
    window.localStorage.setItem(languageStorageKey, language)
  }, [language])

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    toggleLanguage: () => setLanguage((current) => current === 'en' ? 'th' : 'en'),
    translate: (text) => {
      if (language === 'en') return text
      const leadingWhitespace = text.match(/^\s*/)?.[0] ?? ''
      const trailingWhitespace = text.match(/\s*$/)?.[0] ?? ''
      const normalizedText = text.trim().replace(/\s+/g, ' ')
      const translation = thaiTranslations[normalizedText]
      return translation ? `${leadingWhitespace}${translation}${trailingWhitespace}` : text
    },
  }), [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  return useContext(LanguageContext)
}

const translatedStringProps = new Set([
  'alt',
  'aria-label',
  'capability',
  'description',
  'error',
  'eyebrow',
  'label',
  'placeholder',
  'title',
])

function localizeNode(node: ReactNode, translate: (text: string) => string): ReactNode {
  if (typeof node === 'string') return translate(node)
  if (Array.isArray(node)) return (node as ReactNode[]).map((child) => localizeNode(child, translate))
  if (!isValidElement<Record<string, unknown>>(node)) return node

  const nextProps: Record<string, unknown> = {}
  for (const [key, value] of Object.entries(node.props)) {
    if (translatedStringProps.has(key) && typeof value === 'string') {
      nextProps[key] = translate(value)
    }
  }
  if (!('children' in node.props)) return cloneElement(node, nextProps)

  const localizedChildren = localizeNode(node.props.children as ReactNode, translate)
  return Array.isArray(localizedChildren)
    ? cloneElement(node, nextProps, ...(localizedChildren as ReactNode[]))
    : cloneElement(node, nextProps, localizedChildren)
}

export function Localize({ children }: { children: ReactNode }) {
  const { translate } = useLanguage()
  return <>{localizeNode(children, translate)}</>
}
